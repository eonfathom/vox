"""Build common_words.txt: the "is this a real word?" list learn.py uses.

Vox must never "fix" a real word into a learned name (lift -> Lyft), and a
misheard form that is itself a real word (Karen, poles) must never become a
blind find/replace correction. Both checks need a word list, and the speech
models already on this machine carry a large one: every whole-word token
(leading-space token, letters only) in their tokenizers is a word or name that
is frequent in their training text. The union of Whisper's, Qwen's and
Voxtral's vocabularies is ~53k entries - English plus common names and some
other languages, which only makes the check more conservative.

Reads tokenizer files from the Hugging Face cache (or the paths given) and
writes common_words.txt next to dictation.py, one lowercase word per line.

    python tools/build_wordlist.py [tokenizer.json|tekken.json|vocab.txt ...]
"""
import base64
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, "common_words.txt")
_WORD = re.compile(r"[A-Za-z]{2,}")


def tokens(path):
    name = os.path.basename(path)
    if name == "tokenizer.json":
        vocab = json.load(open(path, encoding="utf-8"))["model"]["vocab"]
        return [t[0] for t in vocab] if isinstance(vocab, list) else list(vocab)
    if name == "tekken.json":
        out = []
        for t in json.load(open(path, encoding="utf-8"))["vocab"]:
            s = base64.b64decode(t["token_bytes"]).decode("utf-8", "replace")
            out.append("Ġ" + s[1:] if s.startswith(" ") else s)
        return out
    if name == "vocab.txt":
        return [ln.split()[0] for ln in open(path, encoding="utf-8") if ln.strip()]
    return []


def main(paths):
    if not paths:
        hub = os.path.join(os.path.expanduser("~"), ".cache", "huggingface", "hub")
        paths = [p for pat in ("tokenizer.json", "tekken.json", "vocab.txt")
                 for p in glob.glob(os.path.join(hub, "models--*", "snapshots",
                                                 "*", pat))]
    words = set()
    for p in paths:
        try:
            toks = tokens(p)
        except Exception as e:  # a broken cache entry is skipped, not fatal
            print(f"skip {p}: {e}")
            continue
        n = 0
        for t in toks:
            # "Ġ" (GPT-2 byte-level) / "▁" (sentencepiece) = word start
            if t[:1] in ("Ġ", "▁") and _WORD.fullmatch(t[1:]):
                words.add(t[1:].lower())
                n += 1
        print(f"{n:6d} word tokens  {p}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by tools/build_wordlist.py from speech-model "
                "tokenizer vocabularies; see learn.py.\n")
        for w in sorted(words):
            f.write(w + "\n")
    print(f"{len(words)} words -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1:])
